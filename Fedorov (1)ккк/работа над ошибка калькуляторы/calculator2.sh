#!/bin/bash
read -p "Введите первое число: " a
read -p "Введите второе число: " b
read -p "Введите операцию (+, -, *, /): " op

case "$op" in
    +) echo "Результат: $a + $b = $(( a+ b)) " ;;
    -) echo "Результат: $a - $b = $((a - b)) " ;;
    \*) echo "Результат: $a * $b = $((a * b)) " ;;
    /) echo "Результат: $a / $b = $((a / b)) " ;;
    *) echo "Неизвестная операция" ;;
esac


